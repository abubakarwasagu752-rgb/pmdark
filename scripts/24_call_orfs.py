import json
import shutil
import subprocess
import sys
import time
from collections import defaultdict
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "src"))

from pmdark import config as cfgmod  # noqa: E402


def log(m: str) -> None:
    print(f"[{time.strftime('%H:%M:%S')}] {m}", flush=True)


def working_perl() -> str | None:
    """conda's Perl cannot start under a prefix containing '@'. See
    21_align_assemble.py:working_perl for the full diagnosis."""
    for cand in ("/usr/bin/perl", "/bin/perl", shutil.which("perl")):
        if not cand or not Path(cand).exists():
            continue
        try:
            r = subprocess.run([cand, "-e", "print 1"],
                               capture_output=True, text=True, timeout=30)
            if r.returncode == 0 and r.stdout.strip() == "1":
                return cand
        except (OSError, subprocess.TimeoutExpired):
            continue
    return None


def find_diamond(explicit: str | None = None) -> str | None:
    """Locate the diamond binary without changing this process's PATH.

    Same search as 30b_identity_tiers.py: prepending another conda env's
    bin/ to PATH also shadows `python`. diamond was installed into the
    busco env, not pmbio, which is why TransDecoder's bare `diamond` call
    died with "No such file or directory".
    """
    import os
    for cand in (explicit, os.environ.get("DIAMOND"), shutil.which("diamond")):
        if cand and Path(cand).exists():
            return cand
    home = Path.home()
    for env in ("busco", "pmbio"):
        p = home / "pmdark_work" / "envs" / env / "bin" / "diamond"
        if p.exists():
            return str(p)
    return None


SHIM = """#!/bin/bash
# Auto-generated by scripts/24_call_orfs.py. Do not edit.
#
# Two jobs:
#   1. Put `diamond` on TransDecoder's PATH without putting anything ELSE
#      from the busco env there. Prepending busco/bin wholesale switched
#      gtf_to_alignment_gff3.pl onto busco's Perl via its
#      `#!/usr/bin/env perl` shebang, and that Perl has no URI::Escape.
#   2. Force the thread count. This TransDecoder build has no --CPU flag
#      and hard-codes `-p 1`, which would run the Swiss-Prot search
#      single-threaded for hours.
REAL="__REAL__"
THREADS="__THREADS__"
out=(); skip=0
for a in "$@"; do
  if [ "$skip" = 1 ]; then skip=0; continue; fi
  case "$a" in
    -p|--threads) skip=1 ;;
    *) out+=("$a") ;;
  esac
done
exec "$REAL" ${out[@]+"${out[@]}"} --threads "$THREADS"
"""


def make_diamond_shim(workdir: Path, real: str, threads: int) -> Path:
    """A directory containing only a thread-forcing `diamond`."""
    d = workdir / "shim"
    d.mkdir(parents=True, exist_ok=True)
    f = d / "diamond"
    f.write_text(SHIM.replace("__REAL__", real)
                     .replace("__THREADS__", str(threads)))
    f.chmod(0o755)
    return d


def build_homology_db(cfg, workdir: Path, source: str) -> Path | None:
    """Assemble the protein set used as ORF-retention evidence.

    WHY THIS CHANGED, AND IT IS THE MOST CONSEQUENTIAL FIX SO FAR

      The first run used Swiss-Prot alone. When I wrote that, I noted the
      asymmetry it creates -- homology can only rescue an ORF that HAS a
      hit, so known proteins get a second chance and dark ones survive on
      coding score alone -- and I called the bias conservative and safe.

      32_missed_forensics.py shows it was neither. Of the 35
      expressed-but-undetected genes above 1000 TPM, 29 (82.9%) are
      TRANSCRIPT_NO_ORF: the transcript was assembled and no ORF was
      called. Their median annotated length is 116 aa, and the list is led
      by chelonianin-like and WAP four-disulfide-core proteins -- the
      crustin domain family -- plus 14 "uncharacterized LOC..." genes.

      An uncharacterized gene has no Swiss-Prot homolog BY DEFINITION. So
      Swiss-Prot evidence rescued every well-characterised gene on a
      transcript while leaving the lineage-restricted short secreted
      effectors to compete on a Markov coding score that rises with
      length. The bias did not shrink the dark set conservatively; it
      deleted precisely the class the project is about.

      The species' own RefSeq proteome contains those uncharacterized
      proteins, so using it as evidence lets TransDecoder retain the
      correct ORF at those loci. This is also what TransDecoder's own
      documentation advises: search a protein database relevant to the
      organism, not merely a curated one.

      ON CIRCULARITY. Reference-guided ORF retention makes "recovery of
      reference genes" partly self-fulfilling, so recovery is QC here and
      not a result. The novel arm is unaffected by construction: a locus
      absent from the annotation has no reference homolog, so it gains
      nothing from this evidence and the dark set stays as honest as it
      was. The Swiss-Prot-only numbers are kept for comparison.
    """
    import gzip
    parts: list[Path] = []

    if source in ("reference", "both"):
        refp = next(iter(cfg.p("genome").glob("*_protein.faa")), None)
        if refp:
            parts.append(refp)
            log(f"homology evidence: {refp.name} (conspecific RefSeq)")
        else:
            log("WARNING no *_protein.faa in the work tier; "
                "run scripts/27_recovery_exact.py to stage it")

    if source in ("sprot", "both"):
        sprot = cfg.p("raw", "uniprot") / "uniprot_sprot.fasta.gz"
        plain = workdir / "uniprot_sprot.fasta"
        if sprot.exists() and not plain.exists():
            log("decompressing Swiss-Prot")
            with gzip.open(sprot, "rt") as i, plain.open("w") as o:
                shutil.copyfileobj(i, o)
        if plain.exists():
            parts.append(plain)
            log(f"homology evidence: {plain.name}")

    if not parts:
        return None
    if len(parts) == 1:
        return parts[0]

    combined = workdir / f"homology_{source}.faa"
    if not combined.exists() or combined.stat().st_size == 0:
        log(f"concatenating {len(parts)} protein sets -> {combined.name}")
        with combined.open("w") as o:
            for p in parts:
                with p.open() as i:
                    shutil.copyfileobj(i, o)
                o.write("\n")
    return combined


KEEP_ON_WIPE = ("uniprot_sprot.fasta",)


def invalidate_if_stale(workdir: Path, gtf: Path, force: bool) -> bool:
    """Wipe TransDecoder's working directory when its input has changed.

    THE FAILURE THIS PREVENTS, WHICH ALREADY HAPPENED ONCE

      TransDecoder.LongOrfs writes
        <cdna>.transdecoder_dir/__checkpoints_longorfs/TD.longorfs.ok
      and on a later run it sees that file and does nothing. That is
      correct for resuming an interrupted run and catastrophic when the
      INPUT has changed.

      After re-merging with -G, the cDNA was regenerated from a new GTF,
      LongOrfs skipped extraction, and longest_orfs.pep still held
      transcript IDs from the previous merge. Re-merging reassigns MSTRG
      identifiers, so those IDs mostly did not exist in the new alignment
      GFF3: 15,848 of 21,437 proteins came out with no genomic
      coordinates, the 5,589 "placed" were coincidental ID collisions, and
      locus-aware detection read 0.0%. The protein count was byte
      identical to the previous run, which is the signature to watch for.

      Deleting the DONE marker is not enough — the checkpoints are what
      matter. So the input GTF is fingerprinted here, and any change wipes
      the working directory. The homology FASTA is kept, because
      decompressing Swiss-Prot again costs minutes for nothing.

    Returns True if anything was wiped.
    """
    import hashlib
    h = hashlib.md5()
    with gtf.open("rb") as fh:
        for chunk in iter(lambda: fh.read(1 << 20), b""):
            h.update(chunk)
    fp = h.hexdigest()

    stamp = workdir / "INPUT.md5"
    prev = stamp.read_text().strip() if stamp.exists() else None
    if prev == fp and not force:
        return False

    if prev is not None and prev != fp:
        log(f"input GTF changed ({prev[:8]} -> {fp[:8]}); "
            "wiping stale TransDecoder state")
    elif force:
        log("--force: wiping TransDecoder state")

    for child in sorted(workdir.iterdir()) if workdir.exists() else ():
        if child.name in KEEP_ON_WIPE or child.name.startswith("homology_"):
            continue
        if child.name == "shim":
            continue
        try:
            shutil.rmtree(child) if child.is_dir() else child.unlink()
        except OSError as e:
            log(f"  could not remove {child.name}: {e}")

    workdir.mkdir(parents=True, exist_ok=True)
    stamp.write_text(fp + "\n")
    return True


def invalidate_downstream(cfg) -> None:
    """Drop caches keyed to the protein set we are about to replace.

    27/29/32 reuse ref_vs_ours*.tsv and the diamond database of our
    proteins. A new protein set makes all of them wrong, and silently so:
    the files still parse, the IDs just no longer mean the same thing.
    """
    out = cfg.p("proteins")
    gone = []
    for pat in ("ref_vs_ours.tsv", "ref_vs_ours_multi.tsv",
                "ourprots.dmnd", "compare/*"):
        for p in out.glob(pat):
            try:
                shutil.rmtree(p) if p.is_dir() else p.unlink()
                gone.append(p.name)
            except OSError:
                pass
    if gone:
        log(f"invalidated {len(gone)} downstream cache(s): "
            + ", ".join(sorted(set(gone))[:6]))


def perl_has(perl: str, module: str) -> bool:
    try:
        r = subprocess.run([perl, f"-M{module}", "-e", "print 1"],
                           capture_output=True, text=True, timeout=60)
        return r.returncode == 0 and r.stdout.strip() == "1"
    except (OSError, subprocess.TimeoutExpired):
        return False


def supports_flag(cmd: list[str], flag: str) -> bool:
    """Does this TransDecoder build advertise `flag`?

    The unified driver's option set differs between 5.x, 6.x and 7.x.
    Probing the help text is cheaper than guessing and failing four
    minutes into a run.
    """
    try:
        r = subprocess.run([str(c) for c in cmd] + ["--help"],
                           capture_output=True, text=True, timeout=120)
    except (OSError, subprocess.TimeoutExpired):
        return False
    return flag in (r.stdout + r.stderr)


def tool(name: str, perl: str | None) -> list[str]:
    path = shutil.which(name)
    if not path:
        raise RuntimeError(f"{name} not on PATH")
    head = Path(path).read_bytes()[:64].decode("utf-8", "ignore")
    if head.startswith("#!") and "perl" in head.split("\n")[0]:
        if perl is None:
            raise RuntimeError(f"{name} is Perl but no working Perl found")
        return [perl, path]
    return [path]


def run(cmd: list, cwd: Path | None = None,
        extra_path: str | None = None) -> int:
    log("$ " + " ".join(str(c) for c in cmd)[:240])
    env = None
    if extra_path:
        import os
        env = dict(os.environ)
        # Scoped to the child only. Changing this process's PATH would
        # shadow `python` with the other env's interpreter — the mistake
        # that broke an earlier run.
        env["PATH"] = extra_path + os.pathsep + env.get("PATH", "")
    return subprocess.run([str(c) for c in cmd], cwd=cwd, env=env).returncode


def read_fasta_lengths(fa: Path) -> dict[str, int]:
    out: dict[str, int] = {}
    cur, n = None, 0
    with fa.open() as fh:
        for line in fh:
            if line.startswith(">"):
                if cur:
                    out[cur] = n
                cur, n = line[1:].split()[0], 0
            else:
                # TransDecoder appends '*' for the stop codon on complete
                # ORFs. Counting it would push 69 aa proteins over a 70 aa
                # threshold, so the headline band would be off by the
                # number of complete ORFs at exactly the boundary.
                n += len(line.strip().rstrip("*").replace("*", ""))
    if cur:
        out[cur] = n
    return out


def gene_spans(gff: Path) -> dict:
    """chrom -> list of (start, end) for annotated genes."""
    spans = defaultdict(list)
    with gff.open() as fh:
        for line in fh:
            if line.startswith("#"):
                continue
            p = line.split("\t")
            if len(p) > 4 and p[2] == "gene":
                spans[p[0]].append((int(p[3]), int(p[4])))
    for c in spans:
        spans[c].sort()
    return spans


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--gtf", type=Path, default=None,
                    help="default: proteins/merged_filtered.gtf")
    ap.add_argument("--min-aa", type=int, default=70)
    ap.add_argument("--threads", type=int, default=16)
    ap.add_argument("--no-homology", action="store_true",
                    help="skip the DIAMOND-guided ORF retention step")
    ap.add_argument("--homology-source", default="both",
                    choices=["sprot", "reference", "both"],
                    help="protein set used as ORF-retention evidence. "
                         "'sprot' reproduces the first run, which deleted "
                         "short uncharacterized effectors; see "
                         "build_homology_db for why 'both' is the default.")
    ap.add_argument("--diamond", default=None,
                    help="path to the diamond binary (default: search "
                         "$DIAMOND, PATH, then the busco/pmbio envs)")
    ap.add_argument("--force", action="store_true")
    args = ap.parse_args()

    cfg = cfgmod.load()
    out = cfg.p("proteins")
    gtf = args.gtf or (out / "merged_filtered.gtf")
    if not gtf.exists():
        raise SystemExit(f"missing {gtf} — run scripts/23c_filter_transcripts.py")

    genome = next(iter(cfg.p("genome").glob("*_genomic.fna")), None)
    if genome is None:
        raise SystemExit("genome FASTA not found in the work tier")

    perl = working_perl()
    log(f"perl   : {perl}")

    # TransDecoder's util/*.pl scripts are launched by their own
    # `#!/usr/bin/env perl` shebang, NOT by the perl above, so the Perl that
    # matters for them is whichever one PATH resolves. Gene_obj.pm needs
    # URI::Escape; busco's Perl lacks it and pmbio's has it. Check now
    # rather than failing one second into the run.
    env_perl = shutil.which("perl")
    if env_perl and not perl_has(env_perl, "URI::Escape"):
        log(f"FATAL: {env_perl} (the perl PATH resolves) has no URI::Escape,")
        log("  which TransDecoder's PerlLib/Gene_obj.pm requires.")
        log("  Activate the pmbio env, whose perl has it:")
        log("    conda activate ~/pmdark_work/envs/pmbio")
        return 1
    log(f"env perl: {env_perl} (has URI::Escape)")
    log(f"gtf    : {gtf.name}")
    log(f"genome : {genome.name}")
    log(f"min ORF: {args.min_aa} aa")

    workdir = out / "transdecoder"
    workdir.mkdir(parents=True, exist_ok=True)

    # Fingerprint the input before anything reads a checkpoint.
    wiped = invalidate_if_stale(workdir, gtf, args.force)
    if wiped:
        invalidate_downstream(cfg)

    td = tool("TransDecoder", perl)
    cmd = td + [
        "--genome", genome,
        "--gtf", gtf,
        "-m", args.min_aa,
        "--output_dir", workdir,
    ]

    # This build has no --CPU flag (probed). Threading is forced through the
    # diamond shim below instead, so the Swiss-Prot search still gets all
    # the cores.
    if supports_flag(td, "--CPU"):
        cmd += ["--CPU", args.threads]
        log(f"threads: {args.threads} via --CPU")

    # Homology evidence lets TransDecoder keep ORFs that a coding-potential
    # score alone would discard. Worth the extra runtime: small AMP ORFs
    # are exactly the ones a length-biased scorer tends to drop.
    #
    # Note the asymmetry this introduces, which belongs in the methods:
    # homology can only rescue ORFs that HAVE a Swiss-Prot hit, so known
    # proteins get a second chance and dark ones survive on coding score
    # alone. That biases the dark set toward conservatism — it can only
    # shrink it, never inflate it — which is the safe direction for a
    # dark-proteome claim.
    extra_path = None
    if not args.no_homology:
        dmnd = find_diamond(args.diamond)
        if dmnd is None:
            log("diamond not found in $DIAMOND, PATH or the busco/pmbio "
                "envs — continuing WITHOUT homology evidence")
            log("  (pass --diamond /path/to/diamond to enable it)")
        else:
            plain = build_homology_db(cfg, workdir, args.homology_source)
            if plain is not None and plain.exists():
                cmd += ["--blast_search_pep", plain, "--blast_tool", "diamond"]
                # TransDecoder shells out to a bare `diamond`, so it must be
                # on the CHILD's PATH. Expose ONLY diamond, through a shim
                # dir: prepending busco/bin wholesale put busco's Perl ahead
                # of pmbio's and broke gtf_to_alignment_gff3.pl, which needs
                # URI::Escape. The shim also forces the thread count.
                extra_path = str(make_diamond_shim(workdir, dmnd, args.threads))
                log(f"homology: {dmnd}")
                log(f"  exposed via shim {extra_path} at {args.threads} threads")
            else:
                log("no homology protein set available — skipping homology")

    marker = workdir / "DONE"
    if marker.exists() and not args.force and not wiped:
        log("TransDecoder output present; skipping (--force to rerun)")
    else:
        rc = run(cmd, cwd=workdir, extra_path=extra_path)
        if rc != 0:
            log(f"TransDecoder exited {rc}")
            log("LongOrfs checkpoints are kept, so a rerun resumes from the "
                "failed stage rather than starting over")
            log("if the failure is in the homology search, rerun with "
                "--no-homology to get a coding-score-only protein set")
            return 1
        marker.write_text(time.strftime("%F %T") + "\n")

    pep = next(iter(workdir.glob("**/*.transdecoder.pep")), None)
    if pep is None:
        pep = next(iter(workdir.glob("**/longest_orfs.pep")), None)
    if pep is None:
        log("no .pep output found; inspect " + str(workdir))
        return 1
    log(f"proteins: {pep}")

    lens = read_fasta_lengths(pep)
    n70 = sum(1 for L in lens.values() if L >= 70)
    n100 = sum(1 for L in lens.values() if L >= 100)
    band = n70 - n100

    print("\n" + "=" * 74)
    print("ORF CALLING")
    print("=" * 74)
    print(f"  total predicted proteins       {len(lens):,}")
    print(f"  >= 100 aa (upstream cutoff)    {n100:,}")
    print(f"  >= 70 aa  (this study)         {n70:,}")
    print(f"  70-99 aa  RECOVERED            {band:,}   "
          f"({100*band/max(1,n70):.1f}% of the set)")
    print(f"\n  upstream reported 28,423 proteins at >= 100 aa")
    print(f"  ours at the same cutoff: {n100:,} "
          f"({n100/28423:.2f}x)")

    # Split the 70-99 aa band out: these are the AMP-candidate space and
    # deserve their own file for the secretion/AMP screens in Aim 3.
    short_fa = out / "proteins_70to99aa.faa"
    keep = {k for k, L in lens.items() if 70 <= L < 100}
    w = False
    with pep.open() as fh, short_fa.open("w") as o:
        for line in fh:
            if line.startswith(">"):
                w = line[1:].split()[0] in keep
            if w:
                o.write(line)
    log(f"wrote {short_fa.name} ({len(keep):,} sequences)")

    # Aim 4's 5' GAS-motif scan needs each ORF's transcript in genome
    # coordinates. --genome/--gtf produces this for free; check it landed.
    gen_gff = next(iter(workdir.glob("**/*.transdecoder.genome.gff3")), None)
    if gen_gff:
        print(f"\n  genome-coordinate GFF3: {gen_gff.name}")
    else:
        print("\n  WARNING: no *.transdecoder.genome.gff3 — the GAS-motif")
        print("  scan in Aim 4 will have no genomic positions to work from")

    report = {
        "min_aa": args.min_aa,
        "homology_evidence": extra_path is not None,
        "homology_source": args.homology_source,
        "genome_gff3": str(gen_gff) if gen_gff else None,
        "pep_file": str(pep),
        "n_total": len(lens),
        "n_ge_70": n70,
        "n_ge_100": n100,
        "n_70_to_99_recovered": band,
        "upstream_n_ge_100": 28423,
    }
    rp = cfg.p("results") / "orf_calling.json"
    rp.write_text(json.dumps(report, indent=2))
    print(f"\nwrote {rp}")
    print("\nNext: proteinness filter (ESM-2 pseudo-perplexity vs shuffled")
    print("and frameshifted decoys), then the three dark-set definitions.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
