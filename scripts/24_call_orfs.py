#!/usr/bin/env python3
"""ORF calling with TransDecoder, at 70 aa and 100 aa for comparison.

    python scripts/24_call_orfs.py --threads 16
    python scripts/24_call_orfs.py --min-aa 70 --no-homology

WHY 70 aa

  The upstream study used TransDecoder at >= 100 aa. Penaeid antimicrobial
  peptides mature at 5-12 kDa: penaeidins, crustins and ALFs have
  precursors near or below 100 aa. A 100 aa floor therefore removes, by
  construction, the lineage-restricted small secreted effectors that Aim 3
  exists to find — and the study would then report their absence.

  This runs at 70 aa and records which proteins fall in the 70-99 aa band,
  so the recovered space is an explicit, quotable number rather than a
  silent parameter choice. The >= 100 aa subset is retained so results stay
  directly comparable with the published set.

TWO IMPLEMENTATION NOTES

  * TransDecoder is a Perl script, and conda's Perl is broken in this
    environment because the env prefix contains '@cpe' (Perl parses it as
    an array variable). The same system-Perl detection used in
    21_align_assemble.py applies here.

  * Running with --genome and --gtf rather than -t makes TransDecoder
    extract cDNA itself and PROPAGATE FINAL ORFs BACK TO GENOME
    COORDINATES. That is free and we need it: the 5' GAS-motif scan in
    Aim 4 requires genomic positions for each ORF's transcript.
"""

from __future__ import annotations

